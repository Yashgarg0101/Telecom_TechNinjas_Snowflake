CREATE OR REPLACE TABLE CDR_VALID(
    CALLID STRING,
    CALLER_NO STRING,
    RECEIVER STRING,
    DURATION NUMBER,
    CALLTYPE STRING,
    TOWERID STRING,
    CALL_TIME TIMESTAMP,
    REVENUE FLOAT,
    ISINTERNATIONAL INT
);


INSERT INTO CDR_VALID
SELECT 
    C.CALLID,
    C.CALLER_NO,
    C.RECEIVER,
    COALESCE(TRY_TO_NUMBER(C.DURATION),0),
    C.CALLTYPE,
    C.TOWERID,
    TRY_TO_TIMESTAMP(C.TIME_STAMP),
    COALESCE(TRY_TO_NUMBER(C.DURATION),0)*0.02,
    CASE WHEN C.CALLTYPE='INT' THEN 1 ELSE 0 END
FROM CDR_RAW C
LEFT JOIN CUSTOMER_MASTER CM
    ON C.CALLER_NO = CM.PHONENUMBER
LEFT JOIN TOWER_MASTER TM
    ON C.TOWERID = TM.TOWERID
QUALIFY ROW_NUMBER() OVER 
(PARTITION BY C.CALLID ORDER BY TRY_TO_TIMESTAMP(C.TIME_STAMP) DESC)=1;

CREATE OR REPLACE STREAM CDR_STREAM 
ON TABLE CDR_VALID;

CREATE OR REPLACE TABLE FACT_CDR(
    ID INT AUTOINCREMENT,
    CALLID STRING,
    CALLER_NO STRING,
    RECEIVER STRING,
    DURATION NUMBER,
    REVENUE FLOAT,
    ISINTERNATIONAL INT,
    CALLDATE DATE
);

MERGE INTO FACT_CDR T
USING (
    SELECT 
        CALLID,
        CALLER_NO,
        RECEIVER,
        DURATION,
        REVENUE,
        ISINTERNATIONAL,
        CAST(CALL_TIME AS DATE) AS CALLDATE
    FROM CDR_VALID
) S
ON T.CALLID = S.CALLID

WHEN NOT MATCHED THEN
INSERT (
    CALLID,
    CALLER_NO,
    RECEIVER,
    DURATION,
    REVENUE,
    ISINTERNATIONAL,
    CALLDATE
)
VALUES (
    S.CALLID,
    S.CALLER_NO,
    S.RECEIVER,
    S.DURATION,
    S.REVENUE,
    S.ISINTERNATIONAL,
    S.CALLDATE
);

INSERT INTO CDR_VALID SELECT * FROM CDR_VALID;

CREATE OR REPLACE TASK TELECOM_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = '5 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA('CDR_STREAM')
AS

MERGE INTO FACT_CDR T
USING (
    SELECT 
        CALLID,
        CALLER_NO,
        RECEIVER,
        DURATION,
        REVENUE,
        ISINTERNATIONAL,
        CAST(CALL_TIME AS DATE) AS CALLDATE
    FROM CDR_STREAM
) S
ON T.CALLID = S.CALLID

WHEN NOT MATCHED THEN
INSERT (
    CALLID,
    CALLER_NO,
    RECEIVER,
    DURATION,
    REVENUE,
    ISINTERNATIONAL,
    CALLDATE
)
VALUES (
    S.CALLID,
    S.CALLER_NO,
    S.RECEIVER,
    S.DURATION,
    S.REVENUE,
    S.ISINTERNATIONAL,
    S.CALLDATE
);

ALTER TASK TELECOM_TASK RESUME;

EXECUTE TASK TELECOM_TASK;

