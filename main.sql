CREATE OR REPLACE VIEW VW_KPI_SUMMARY AS
SELECT 
    COUNT(*) AS TOTAL_CALLS,
    SUM(REVENUE) AS TOTAL_REVENUE,
    AVG(DURATION) AS AVG_CALL_DURATION,
    SUM(REVENUE) / COUNT(*) AS REVENUE_PER_CALL
FROM FACT_CDR;

CREATE OR REPLACE VIEW VW_TOP_CALLERS AS
SELECT 
    CALLER_NO,
    COUNT(*) AS TOTAL_CALLS,
    SUM(REVENUE) AS TOTAL_REVENUE
FROM FACT_CDR
GROUP BY CALLER_NO
ORDER BY TOTAL_CALLS DESC;

CREATE OR REPLACE VIEW VW_DAILY_REVENUE AS
SELECT 
    CALLDATE,
    SUM(REVENUE) AS TOTAL_REVENUE
FROM FACT_CDR
GROUP BY CALLDATE;

CREATE OR REPLACE VIEW VW_INT_CALLS AS
SELECT COUNT(*) AS INT_CALLS
FROM FACT_CDR
WHERE ISINTERNATIONAL = 1;

CREATE OR REPLACE VIEW VW_LOCAL_CALLS AS
SELECT COUNT(*) AS LOCAL_CALLS
FROM FACT_CDR
WHERE ISINTERNATIONAL = 0;

SELECT 
    CALLDATE,
    SUM(REVENUE) AS DAILY_REVENUE
FROM FACT_CDR
GROUP BY CALLDATE
ORDER BY CALLDATE;

SELECT 
    CASE 
        WHEN ISINTERNATIONAL = 1 THEN 'International'
        ELSE 'Local'
    END AS CALL_TYPE,
    COUNT(*) AS TOTAL_CALLS
FROM FACT_CDR
GROUP BY CALL_TYPE;

